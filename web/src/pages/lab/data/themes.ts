// Mood-based buckets used to organize the theme dropdown (and to support
// future "show me a random pastel" style filters). Loosely modeled on Adobe
// Color's trend categories — Vibrant/Light/Dark/Muted/Deep — adapted for a
// caption-renderer context where dark backgrounds dominate.
export type ThemeCategory =
  | 'cinematic' // yellow-forward caption standard (broadcast, film, YouTube)
  | 'vibrant' // saturated, energetic
  | 'neon' // high-contrast pops on near-black (vaporwave / synthwave)
  | 'pastel' // soft / low-saturation accents on a dark stage
  | 'editorial' // sophisticated, magazine, restrained palette
  | 'earth' // warm natural, organic
  | 'retro' // 70s/80s vintage moods
  | 'mono' // single-hue family
  | 'light'; // light background (rare — kept tight for legibility)

